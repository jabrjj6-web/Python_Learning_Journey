print("--- 🔢 Number Multiplier Loop 🔢 ---")

# تعريف مصفوفة الأرقام
numbers = [1, 2, 3, 4, 5]

print("Processing numbers...")
print("----------------------------------")

# تكرار لضرب كل رقم في 2 وطباعته
for num in numbers:
    result = num * 2
    print(f"Original number: {num} -> After multiplication (*2): {result} ✅")
