print("--- List Element Insertion Demo ---\n")

# قائمة الفواكه بالتهجئة الصحيحة
fruits = ["apple", "banana", "orange"]

# طباعة القائمة قبل إدراج عنصر جديد
print(f"Original List: {fruits}")

# إدراج الكيوي في أول القائمة (Index 0)
fruits.insert(0, "kiwi")

# طباعة القائمة بعد الإدراج
print(f"Updated List:  {fruits}")
